const pool = (theme: string) => STOCK.filter(s => s.theme === theme);
export function stockFor(key: string, theme: string): Stock {
  const p = pool(theme).length ? pool(theme) : STOCK;
  let h = 0; for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return p[h % p.length];
}
